const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..'), source = fs.readFileSync(path.join(root, 'assets/community.js'), 'utf8');
const unit = name => source.match(new RegExp('  function ' + name + '\\([^]*?\\n  }'))[0];
let focused = null;
const values = { id: 'my-draft', kind: 'discussion', target: 'demo', heading: 'Titre', body: 'Contenu', rating: '', parent: '' };
const fields = Object.fromEntries(Object.entries(values).map(([key, value]) => [key, { value, attrs: {}, setAttribute(k,v) { this.attrs[k]=v; }, removeAttribute(k) { delete this.attrs[k]; }, focus() { focused=key; } }]));
for (const key of ['titleField','ratingField','parentField']) fields[key] = {};
const context = { submissionFields: fields, catalogItems: [{id:'demo'}], ID_RE: /^[a-z0-9][a-z0-9._-]{1,127}$/, submissionPreview: {}, submissionStatus: {}, canonicalText: JSON.stringify };
vm.createContext(context);
vm.runInContext(['buildSubmission','updateSubmissionFields','renderSubmissionPreview'].map(unit).join('\n'), context);
const checks = [];
fields.target.value=''; context.renderSubmissionPreview();
assert.equal(focused,null); assert.equal(fields.target.attrs['aria-invalid'],undefined);
checks.push('Passive preview never marks or focuses an invalid field');
context.renderSubmissionPreview(true);
assert.equal(focused,'target'); assert.equal(fields.target.attrs['aria-invalid'],'true'); assert.match(context.submissionStatus.textContent,/Choisissez un contenu/);
checks.push('Explicit validation focuses and identifies the missing target with an actionable message');
fields.target.value='demo'; fields.body.value='  '; focused=null;
assert.throws(()=>context.buildSubmission(true),/Contenu requis/); assert.equal(focused,'body'); assert.equal(fields.target.attrs['aria-invalid'],undefined);
checks.push('Subsequent validation clears previous errors and identifies whitespace-only content');
fields.body.value='Contenu'; fields.kind.value='review'; fields.rating.value='2.5';
assert.throws(()=>context.buildSubmission(true),/entier/); assert.equal(focused,'rating');
fields.kind.value='comment'; context.updateSubmissionFields();
assert.equal(fields.rating.attrs['aria-invalid'],undefined); assert.equal(fields.ratingField.hidden,true); assert.equal(fields.parent.required,true);
assert.throws(()=>context.buildSubmission(true),/contribution parente/); assert.equal(focused,'parent');
checks.push('Review rating and comment parent errors target the relevant control; hidden rating loses stale invalid state');
fields.parent.value='parent-id'; focused=null;
const valid=context.buildSubmission(true); assert.equal(valid.kind,'comment'); assert.equal(valid.parentSubmissionId,'parent-id'); assert.equal(focused,null);
for (const key of Object.keys(values)) assert.equal(fields[key].attrs['aria-invalid'],undefined);
assert.match(source,/submissionSave[\s\S]*?buildSubmission\(true\)/);
assert.match(source,/submissionExport[\s\S]*?buildSubmission\(true\)/);
checks.push('Valid draft clears invalid markers without focus movement; save and export request interactive validation');
const report={result:'PASS',scope:'Five grouped Node VM source scenarios; not screen-reader proof',checks};
fs.writeFileSync(path.join(__dirname,'submission-focus-checks.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
